// What makes a brain open on its own in Claude Code, from any folder (brain-split HARNESS): the
// program's rules as the brain's own AGENTS.md, the two gate forwarders, a settings.json that loads
// the program's skills and hooks through the `cogby` plugin instead of spelling them one folder up,
// and the `@../AGENTS.md` import in the brain's CLAUDE.md. Setup lays it out, registerPlugin installs
// the plugin for the brain at project scope, and a session start brings the brain's AGENTS.md up to
// the plugin's when the plugin has moved on (agentsStatus here, core/brain/rules.cjs for the write).
//
// Node built-ins only (fs, path, crypto), on purpose: starter-brain.cjs requires this before
// paths.cjs, which throws at module load on two brains or a broken install record, and the CLI loads
// it from the install it is setting up, which may be newer or older than the CLI itself. Nothing
// here spawns a process of its own: registerPlugin is handed the caller's spawner.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const PLUGIN = 'cogby@cogby';
const MARKETPLACE = 'cogby';
const FORWARDERS = Object.freeze(['lane-policy.cjs', 'wrapup-guard.cjs']);
const TEMPLATE = Object.freeze(['core', 'templates', 'starter-brain', '.claude']);
const AGENTS_IMPORT = '@../AGENTS.md';
const TIMEOUT_MS = 120000;

// The seven hook commands every brain's settings.json carried before the plugin, spelled one folder
// up. They work only for a brain directly inside its program, and the plugin now carries the same
// seven, so they are removed once the plugin is in place, and only those exact strings: a hook the
// owner added is never touched.
const SHIPPED_HOOKS = Object.freeze([
  'load-memory-snapshot', 'prompt-pointers', 'skill-usage', 'deliverable-output-nudge',
  'capture-log', 'session-wrapup', 'playwright-shot-dir',
].map((name) => `node "$CLAUDE_PROJECT_DIR"/../.claude/hooks/${name}.cjs`));

const HEADER_PREFIX = /^(?:﻿)?<!-- Generated by Cogby \S+ from the program's AGENTS\.md\./;

const HEADER_VERSION = /^(?:﻿)?<!-- Generated by Cogby (\S+) from the program's AGENTS\.md\./;

const header = (version) => `<!-- Generated by Cogby ${version} from the program's AGENTS.md. Do not edit: ` +
  'a session start rewrites this file when the plugin has been updated. Rules for this brain only go in .claude/CLAUDE.md. -->';

