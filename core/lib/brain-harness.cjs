const samePath = (a, b) => {
  const x = path.resolve(String(a));
  const y = path.resolve(String(b));
  return process.platform === 'win32' ? x.toLowerCase() === y.toLowerCase() : x === y;
};
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const readOrNull = (file) => { try { return fs.readFileSync(file); } catch { return null; } };
const isPlainObject = (value) => !!value && typeof value === 'object' && !Array.isArray(value);
const own = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

function programVersion(engine) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(engine, 'package.json'), 'utf8').replace(/^﻿/, ''));
    if (pkg && typeof pkg.version === 'string' && pkg.version) return pkg.version;
  } catch { /* a fixture, or an engine with no package.json */ }
  return 'unknown';
}

// A rename over the old file, so a reader never sees half of it.
function atomicWrite(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}.${crypto.randomBytes(4).toString('hex')}.tmp`;
  fs.writeFileSync(temporary, data);
  try { fs.renameSync(temporary, file); }
  catch (error) { try { fs.rmSync(temporary, { force: true }); } catch { /* best effort */ } throw error; }
}

// (1) The brain's AGENTS.md: one header line, then the program's AGENTS.md byte for byte. The header
// takes the line ending the program's file uses, so the file has one kind.
function renderAgents(engine, version) {
  const body = fs.readFileSync(path.join(engine, 'AGENTS.md'));
  const nl = body.indexOf(10);
  const eol = nl > 0 && body[nl - 1] === 13 ? '\r\n' : '\n';
  return Buffer.concat([Buffer.from(`${header(version || programVersion(engine))}${eol}`, 'utf8'), body]);
}

// (2) Writes it, atomically. Only a file that carries the header is Cogby's to rewrite: an AGENTS.md
// the owner put there is reported and left as it is.
function writeAgents(brain, { engine, version } = {}) {
  const target = path.join(brain, 'AGENTS.md');
  if (!engine || !fs.existsSync(path.join(engine, 'AGENTS.md'))) return { path: target, written: false, why: 'no-program-agents' };
  const next = renderAgents(engine, version);
  const current = readOrNull(target);
  if (current && !HEADER_PREFIX.test(current.subarray(0, 200).toString('utf8'))) {
    return { path: target, written: false, why: 'owner-file' };
  }
  if (current && current.equals(next)) return { path: target, written: false, unchanged: true };
  atomicWrite(target, next);
  return { path: target, written: true };
}

const unix = (text) => String(text).replace(/^﻿/, '').replace(/\r\n?/g, '\n');
const rulesHash = (text) => crypto.createHash('sha256').update(unix(text), 'utf8').digest('hex');

// 1.2.10 against 1.3.0, as numbers. null when either is not three numbers (a fixture's "unknown").
function compareVersions(a, b) {
  const parts = (v) => { const m = /^(\d+)\.(\d+)\.(\d+)/.exec(String(v || '')); return m ? m.slice(1).map(Number) : null; };
  const [x, y] = [parts(a), parts(b)];
  if (!x || !y) return null;
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1;
  return 0;
}

// (2b) Where a brain's AGENTS.md stands against the plugin's. Reads only.
//   current   the same text, or the same version in its header: nothing to do
//   newer     its header names a later version (the brain was last opened by a newer plugin, on
//             another machine): left alone, so two machines never write it back and forth
//   older     an earlier version, and the rules under the header are ones Cogby shipped: replaced
//   missing   no file. It is the plugin's file, so it is written
//   edited    an earlier version whose rules are not ones Cogby shipped: changed by hand
//   owner     no generated header: the owner's own file
// `from` is the version the header names, `to` the plugin's, `hash` the file as it is (how "said
// once" is remembered).
function agentsStatus(brain, { engine, version } = {}) {
  const target = path.join(brain, 'AGENTS.md');
  if (!engine || !fs.existsSync(path.join(engine, 'AGENTS.md'))) return { state: 'no-program', path: target };
  const to = version || programVersion(engine);
  const current = readOrNull(target);
  if (!current) return { state: 'missing', path: target, from: null, to };
  const text = unix(current.toString('utf8'));
  const hash = sha256(current).slice(0, 16);
  const named = HEADER_VERSION.exec(text.slice(0, 200));
  if (!named) return { state: 'owner', path: target, from: null, to, hash };
  const from = named[1];
  if (from === to || text === unix(renderAgents(engine, to).toString('utf8'))) return { state: 'current', path: target, from, to, hash };
  const order = compareVersions(from, to);
  if (order !== null && order > 0) return { state: 'newer', path: target, from, to, hash };
  const rules = rulesHash(text.slice(text.indexOf('\n') + 1));
  const shipped = KNOWN_AGENTS.includes(rules) || rules === rulesHash(fs.readFileSync(path.join(engine, 'AGENTS.md'), 'utf8'));
  return { state: shipped ? 'older' : 'edited', path: target, from, to, hash };
}

// (3) The brain's settings.json after a refresh. Every key, permission, plugin and hook the owner has
// stays; cogby@cogby is added when the key is absent, and an explicit false is kept and reported. The
// seven shipped hooks go only when `pluginReady`: removing them while the plugin is not loaded would
// leave the brain with no Tier-0, no log capture and no wrap-up.
function mergeSettings(existing, template = {}, { pluginReady = false } = {}) {
  const settings = JSON.parse(JSON.stringify(existing || {}));
  const report = { pluginAdded: false, pluginDisabled: false, hooksRemoved: [], hooksKept: [] };
  const wanted = isPlainObject(template && template.enabledPlugins) && own(template.enabledPlugins, PLUGIN)
    ? template.enabledPlugins[PLUGIN] : true;
  if (settings.enabledPlugins === undefined) settings.enabledPlugins = {};
  if (isPlainObject(settings.enabledPlugins)) {
    if (!own(settings.enabledPlugins, PLUGIN)) { settings.enabledPlugins[PLUGIN] = wanted; report.pluginAdded = true; }
    else if (settings.enabledPlugins[PLUGIN] === false) report.pluginDisabled = true;
  }

  if (isPlainObject(settings.hooks)) {
    let removedAny = false;
    for (const [event, groups] of Object.entries(settings.hooks)) {
      if (!Array.isArray(groups)) continue;
      const kept = [];
      let removedHere = false;
      for (const group of groups) {
        if (!group || !Array.isArray(group.hooks)) { kept.push(group); continue; }
        const hooks = group.hooks.filter((hook) => {
          const shipped = !!hook && hook.type === 'command' && SHIPPED_HOOKS.includes(String(hook.command).trim());
          if (!shipped) return true;
          (pluginReady ? report.hooksRemoved : report.hooksKept).push(hook.command);
          return !pluginReady;
        });
        if (hooks.length === group.hooks.length) kept.push(group);
        else { removedHere = true; if (hooks.length) kept.push({ ...group, hooks }); }
      }
      if (!removedHere) continue;
      removedAny = true;
      if (kept.length) settings.hooks[event] = kept;
      else delete settings.hooks[event];
    }
    if (removedAny && !Object.keys(settings.hooks).length) delete settings.hooks;
  }
  return { settings, changed: JSON.stringify(settings) !== JSON.stringify(existing || {}), ...report };
}

function insertAgentsImport(text) {
  if (/^@\.\.\/AGENTS\.md[ \t]*\r?$/m.test(text)) return null;
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const identity = /^@\.\.\/\.cogby\/self\/(?:SOUL|USER)\.md[ \t]*\r?$/m.exec(text);
  if (identity) return `${text.slice(0, identity.index)}${AGENTS_IMPORT}${eol}${text.slice(identity.index)}`;
  const sep = !text ? '' : text.endsWith('\n') ? eol : `${eol}${eol}`;
  return `${text}${sep}${AGENTS_IMPORT}${eol}`;
}

// (4) Brings a brain's harness up to the program's: AGENTS.md, the forwarders, settings.json and the
// AGENTS import. .codex/, .mcp.json and settings.local.json are the owner's and never touched. A file
// that cannot be read as settings is reported and left alone, never overwritten.
function refreshHarness(brain, { engine, version, pluginReady = false } = {}) {
  const template = path.join(engine, ...TEMPLATE);
  const harness = path.join(brain, '.claude');
  const report = { brain, pluginReady: !!pluginReady, agents: writeAgents(brain, { engine, version }), forwarders: [], settings: null, claudeMd: null };

  for (const name of FORWARDERS) {
    const bytes = readOrNull(path.join(template, 'hooks', name));
    const target = path.join(harness, 'hooks', name);
    if (!bytes) { report.forwarders.push({ name, copied: false, why: 'no-template' }); continue; }
    const current = readOrNull(target);
    if (current && sha256(current) === sha256(bytes)) { report.forwarders.push({ name, copied: false, unchanged: true }); continue; }
    atomicWrite(target, bytes);
    report.forwarders.push({ name, copied: true });
  }

  const settingsFile = path.join(harness, 'settings.json');
  const templateBytes = readOrNull(path.join(template, 'settings.json'));
  let templateSettings = {};
  try { templateSettings = JSON.parse(String(templateBytes || '{}').replace(/^﻿/, '')); } catch { /* merged against nothing */ }
  const currentSettings = readOrNull(settingsFile);
  if (!currentSettings) {
    if (templateBytes) { atomicWrite(settingsFile, templateBytes); report.settings = { written: true, copied: true }; }
    else report.settings = { written: false, why: 'no-template' };
  } else {
    let parsed;
    try { parsed = JSON.parse(currentSettings.toString('utf8').replace(/^﻿/, '')); } catch (error) { parsed = error; }
    if (!isPlainObject(parsed) || parsed instanceof Error) {
      report.settings = { written: false, why: 'unparseable', detail: parsed instanceof Error ? parsed.message : 'not a JSON object' };
    } else {
      const merged = mergeSettings(parsed, templateSettings, { pluginReady });
      if (merged.changed) atomicWrite(settingsFile, `${JSON.stringify(merged.settings, null, 2)}\n`);
      const { settings, changed, ...rest } = merged;
      report.settings = { written: changed, ...rest };
    }
  }

  const rulesFile = path.join(harness, 'CLAUDE.md');
  const rules = readOrNull(rulesFile);
  if (!rules) {
    const templateRules = readOrNull(path.join(template, 'CLAUDE.md'));
    if (templateRules) { atomicWrite(rulesFile, templateRules); report.claudeMd = { written: true, copied: true }; }
    else report.claudeMd = { written: false, why: 'no-template' };
  } else {
    const next = insertAgentsImport(rules.toString('utf8'));
    if (next === null) report.claudeMd = { written: false, unchanged: true };
    else { atomicWrite(rulesFile, next); report.claudeMd = { written: true, inserted: AGENTS_IMPORT }; }
  }
  return report;
}

// ---- (5) the plugin -------------------------------------------------------------------------------

const quote = (value) => (/[\s"'&|<>()^%!$`]/.test(String(value)) ? `"${String(value).replace(/"/g, '\\"')}"` : String(value));

// The two commands that do by hand what registerPlugin does, to be run in the brain folder.
function handCommands(engine, claude = 'claude') {
  return [
    `${quote(claude)} plugin marketplace add ${quote(engine)}`,
    `${quote(claude)} plugin install ${PLUGIN} --scope project`,
  ];
}

function parseList(stdout) {
  try {
    const value = JSON.parse(String(stdout || '').trim());
    if (Array.isArray(value)) return value;
    if (isPlainObject(value)) {
      const list = Object.values(value).find(Array.isArray);
      if (list) return list;
    }
  } catch { /* not JSON: nothing listed */ }
  return [];
}

// The shell could not find claude at all, which no retry fixes: ENOENT on a direct spawn, 127 or
// 9009 or cmd.exe's sentence through a shell.
function notFound(result) {
  if (!result) return false;
  if (result.error && result.error.code === 'ENOENT') return true;
  if (result.status === 127 || result.status === 9009) return true;
  return /is not recognized as an internal or external command|cannot find the path specified|command not found/i
    .test(String(result.stderr || ''));
}

const worked = (result) => !!result && result.status === 0 && !result.error;
const detailOf = (result) => String((result && (result.stderr || result.stdout)) || (result && result.error && result.error.message) || '')
  .trim().split(/\r?\n/).slice(0, 3).join(' ').slice(0, 300);

// Registers the program as the `cogby` marketplace and installs cogby@cogby at project scope for the
// brain: every call runs with the brain as its cwd, because that is the project a project-scope
// install belongs to. Never user scope: that would run the seven hooks in every project on the
// machine, the program folder included. Every call is bounded, and nothing throws: a failure comes
// back as { ok: false, why, commands } with the two commands to run by hand.
function registerPlugin({ engine, brain, claude = 'claude', run, timeoutMs = TIMEOUT_MS } = {}) {
  const commands = handCommands(engine, claude);
  const base = { ok: false, brain, commands, calls: [] };
  if (typeof run !== 'function') return { ...base, why: 'no-runner' };
  const call = (args) => {
    let result;
    try { result = run(claude, args, { cwd: brain, stdio: 'pipe', encoding: 'utf8', timeout: timeoutMs, windowsHide: true }); }
    catch (error) { result = { status: null, error }; }
    result = result || { status: null };
    base.calls.push({ args, status: result.status === undefined ? null : result.status });
    return result;
  };
  try {
    const markets = call(['plugin', 'marketplace', 'list', '--json']);
    if (notFound(markets)) return { ...base, why: 'claude-not-found' };
    const known = worked(markets) ? parseList(markets.stdout).find((m) => m && m.name === MARKETPLACE) : null;
    // A marketplace of this name that reads from another folder (the whole program where the small
    // plugin is wanted, a build folder that has since gone) is replaced, not refreshed: `update`
    // re-reads the folder it already has and would keep serving the old one.
    const elsewhere = !!known && typeof known.path === 'string' && known.path && !samePath(known.path, engine);
    if (elsewhere) {
      const dropped = call(['plugin', 'marketplace', 'remove', MARKETPLACE]);
      if (!worked(dropped)) return { ...base, why: 'marketplace-remove-failed', detail: detailOf(dropped) };
    }
    const listed = !!known && !elsewhere;
    const market = call(listed ? ['plugin', 'marketplace', 'update', MARKETPLACE] : ['plugin', 'marketplace', 'add', engine]);
    if (!worked(market)) return { ...base, why: listed ? 'marketplace-update-failed' : 'marketplace-add-failed', detail: detailOf(market) };
    const plugins = call(['plugin', 'list', '--json']);
    const installed = worked(plugins) && parseList(plugins.stdout).some((p) => p && p.id === PLUGIN
      && p.scope === 'project' && typeof p.projectPath === 'string' && samePath(p.projectPath, brain));
    const plugin = call(installed
      ? ['plugin', 'update', PLUGIN, '--scope', 'project']
      : ['plugin', 'install', PLUGIN, '--scope', 'project']);
    if (!worked(plugin)) return { ...base, why: installed ? 'plugin-update-failed' : 'plugin-install-failed', detail: detailOf(plugin) };
    return { ...base, ok: true, source: engine, marketplace: listed ? 'updated' : elsewhere ? 'moved' : 'added', plugin: installed ? 'updated' : 'installed' };
  } catch (error) {
    return { ...base, why: 'error', detail: String(error && error.message).slice(0, 300) };
  }
}

// ---- (6) which program serves a brain that has no install -----------------------------------------

// `cogby init` lays out a brain with no installed program: the program is the package the command
// itself runs from. The plugin's hooks run from Claude Code's cached copy and have to find it, and
// the install record cannot say (it describes one managed install, which status, update and
// uninstall act on). So init leaves a second file beside it in the per-machine config folder,
// brains.json: { brains: [{ brain, root }] }. .claude/hooks/plugin-hook.cjs reads it last.
const BRAINS_FILE = 'brains.json';

function readPrograms(configDir) {
  try {
    const data = JSON.parse(fs.readFileSync(path.join(configDir, BRAINS_FILE), 'utf8').replace(/^\uFEFF/, ''));
    return isPlainObject(data) && Array.isArray(data.brains) ? data.brains.filter((entry) => isPlainObject(entry)
      && typeof entry.brain === 'string' && typeof entry.root === 'string') : [];
  } catch { return []; }
}

function recordProgram(brain, engine, configDir) {
  const entries = readPrograms(configDir).filter((entry) => !samePath(entry.brain, brain));
  entries.push({ brain: path.resolve(brain), root: path.resolve(engine) });
  // The file also names the person's default brain (core/brain/brain.cjs): kept as it is.
  let rest = {};
  try { const data = JSON.parse(fs.readFileSync(path.join(configDir, BRAINS_FILE), 'utf8').replace(/^\uFEFF/, '')); if (isPlainObject(data)) rest = data; } catch { /* a new file */ }
  atomicWrite(path.join(configDir, BRAINS_FILE), `${JSON.stringify({ ...rest, brains: entries }, null, 2)}\n`);
  return { file: path.join(configDir, BRAINS_FILE), brain: path.resolve(brain), root: path.resolve(engine) };
}

