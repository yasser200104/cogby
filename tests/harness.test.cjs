'use strict';

// A brain's AGENTS.md is the plugin's file, and follows the plugin: a session start replaces a copy
// that came from an older version, commits that one file, and says so. A copy edited by hand, the
// owner's own file and a copy from a newer plugin are left alone.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { ROOT, newBrain, hook, git, cogby } = require('./helpers.cjs');
const harness = require('../core/lib/brain-harness.cjs');

const VERSION = require('../package.json').version;
const RULES = fs.readFileSync(path.join(ROOT, 'AGENTS.md'), 'utf8');
const agentsOf = (box) => path.join(box.brain, 'AGENTS.md');
const start = (box, options) => hook(box, 'brain-context', { source: 'startup', session_id: 's1' }, options);
const commits = (box) => Number(git(box.brain, ['rev-list', '--count', 'HEAD']));
// The file as an older plugin wrote it: that version in the first line, then the rules.
const from = (version, rules = RULES) => `${harness.header(version)}\n${rules}`;

test('the list of shipped rules holds AGENTS.md as it is now', () => {
  // Change AGENTS.md and this fails until its hash is added to KNOWN_AGENTS: every text that was
  // ever released is then on the list, and a brain that holds it is known to be unedited.
  assert.ok(harness.KNOWN_AGENTS.includes(harness.rulesHash(RULES)), `add ${harness.rulesHash(RULES)} to KNOWN_AGENTS in core/lib/brain-harness.cjs`);
  assert.equal(harness.rulesHash(RULES.replace(/\n/g, '\r\n')), harness.rulesHash(RULES), 'line endings do not change the hash');
});

test('versions are compared as numbers', () => {
  assert.equal(harness.compareVersions('0.3.1', '0.3.2'), -1);
  assert.equal(harness.compareVersions('0.10.0', '0.9.9'), 1);
  assert.equal(harness.compareVersions('1.0.0', '1.0.0'), 0);
  assert.equal(harness.compareVersions('unknown', '1.0.0'), null);
});

test('a new brain has the current rules: a session start changes nothing and says nothing', (t) => {
  const box = newBrain(t);
  const before = fs.readFileSync(agentsOf(box));
  assert.match(before.toString('utf8'), new RegExp(`^<!-- Generated by Cogby ${VERSION.replace(/\./g, '\\.')} `));
  const n = commits(box);
  const out = start(box);
  assert.equal(out.code, 0, out.err);
  assert.doesNotMatch(out.out, /AGENTS\.md/);
  assert.ok(fs.readFileSync(agentsOf(box)).equals(before));
  assert.equal(commits(box), n);
});

test('rules from an older version are replaced, committed alone, and said in one line', (t) => {
  const box = newBrain(t);
  const own = path.join(box.brain, '.claude', 'CLAUDE.md');
  fs.appendFileSync(own, '\n- This brain only: invoices go to Amina.\n');
  const ownBefore = fs.readFileSync(own);
  fs.writeFileSync(agentsOf(box), from('0.2.0'));
  git(box.brain, ['add', '-A']);
  git(box.brain, ['commit', '-q', '-m', 'an older brain']);
  const n = commits(box);

  const out = start(box);
  assert.equal(out.code, 0, out.err);
  const said = out.out.split('\n').filter((line) => /AGENTS\.md/.test(line));
  assert.equal(said.length, 1, out.out);
  assert.match(said[0], new RegExp(`updated from version 0\\.2\\.0 to ${VERSION.replace(/\./g, '\\.')}`));
  assert.match(said[0], /committed \([0-9a-f]{7,}\)/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), from(VERSION));
  assert.equal(commits(box), n + 1);
  assert.equal(git(box.brain, ['show', '--name-only', '--format=', 'HEAD']), 'AGENTS.md');
  assert.match(git(box.brain, ['log', '-1', '--format=%s']), /AGENTS\.md follows the plugin \(was 0\.2\.0\)/);
  assert.ok(fs.readFileSync(own).equals(ownBefore), '.claude/CLAUDE.md is never touched');
  assert.equal(git(box.brain, ['status', '--porcelain', '--', 'AGENTS.md']), '');

  // The next start finds it current.
  const again = start(box);
  assert.doesNotMatch(again.out, /AGENTS\.md/);
  assert.equal(commits(box), n + 1);
});

test('an older copy with Windows line endings is still known as Cogby\'s', (t) => {
  const box = newBrain(t);
  fs.writeFileSync(agentsOf(box), from('0.3.0').replace(/\n/g, '\r\n'));
  assert.equal(harness.agentsStatus(box.brain, { engine: ROOT }).state, 'older');
});

test('a session outside the brain updates the default brain\'s rules too', (t) => {
  const box = newBrain(t);
  fs.writeFileSync(agentsOf(box), from('0.3.0'));
  const elsewhere = path.join(box.dir, 'some-folder');
  fs.mkdirSync(elsewhere);
  const out = start(box, { cwd: elsewhere });
  assert.equal(out.code, 0, out.err);
  assert.match(out.out, /AGENTS\.md\) were updated from version 0\.3\.0/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), from(VERSION));
});

test('rules edited by hand are left alone, and that is said once', (t) => {
  const box = newBrain(t);
  const edited = `${from('0.2.0')}\n## Mine\n\n- Always answer in French.\n`;
  fs.writeFileSync(agentsOf(box), edited);
  git(box.brain, ['add', '-A']);
  git(box.brain, ['commit', '-q', '-m', 'my rules']);
  const n = commits(box);

  const first = start(box);
  const said = first.out.split('\n').filter((line) => /AGENTS\.md/.test(line));
  assert.equal(said.length, 1, first.out);
  assert.match(said[0], /came from Cogby 0\.2\.0 and was edited by hand since, so it was left as it is/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), edited);

  const second = start(box);
  assert.doesNotMatch(second.out, /AGENTS\.md/, 'said once');
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), edited);
  assert.equal(commits(box), n);
  assert.equal(git(box.brain, ['status', '--porcelain']), '', 'what was said is remembered outside the history');

  // Edited again: it is a different file, so it is said again.
  fs.appendFileSync(agentsOf(box), '- And in the evening too.\n');
  assert.match(start(box).out, /edited by hand/);
});

test('an AGENTS.md with no generated first line is the owner\'s: left alone, said once', (t) => {
  const box = newBrain(t);
  fs.writeFileSync(agentsOf(box), '# My rules\n\nNothing of Cogby\'s here.\n');
  const first = start(box);
  assert.match(first.out, /is not the one Cogby writes .* so it was left as it is/);
  assert.doesNotMatch(start(box).out, /AGENTS\.md/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), '# My rules\n\nNothing of Cogby\'s here.\n');
});

test('rules from a newer plugin are never written back', (t) => {
  const box = newBrain(t);
  const newer = `${from('99.0.0')}\n- A rule this plugin does not know yet.\n`;
  fs.writeFileSync(agentsOf(box), newer);
  const out = start(box);
  assert.doesNotMatch(out.out, /AGENTS\.md/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), newer);
});

test('the same version is left alone even when the text differs', (t) => {
  const box = newBrain(t);
  const same = `${from(VERSION)}\n- Added by hand at this version.\n`;
  fs.writeFileSync(agentsOf(box), same);
  assert.doesNotMatch(start(box).out, /AGENTS\.md/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), same);
});

test('a missing AGENTS.md is written again and committed', (t) => {
  const box = newBrain(t);
  git(box.brain, ['rm', '-q', 'AGENTS.md']);
  git(box.brain, ['commit', '-q', '-m', 'without rules']);
  const out = start(box);
  assert.match(out.out, /AGENTS\.md\) were missing and were written again/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), from(VERSION));
  assert.equal(git(box.brain, ['show', '--name-only', '--format=', 'HEAD']), 'AGENTS.md');
});

test('a brain that is not a repository gets the file and is told it was not committed', (t) => {
  const box = newBrain(t);
  fs.rmSync(path.join(box.brain, '.git'), { recursive: true, force: true });
  fs.writeFileSync(agentsOf(box), from('0.3.0'));
  const out = start(box);
  assert.match(out.out, /updated from version 0\.3\.0 .* not committed:/);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), from(VERSION));
});

test('`cogby context` alone never rewrites the rules', (t) => {
  const box = newBrain(t);
  fs.writeFileSync(agentsOf(box), from('0.3.0'));
  assert.equal(cogby(box, ['context', '--brain', box.brain]).code, 0);
  assert.equal(fs.readFileSync(agentsOf(box), 'utf8'), from('0.3.0'));
});

// ---- the map file older brains hold ------------------------------------------------------------

const MAP_REL = '.cogby/context-index.md';
const mapOf = (box) => path.join(box.brain, '.cogby', 'context-index.md');
const OLD_MAP = [
  '# Context index', '', '<!-- generated by core/lib/context-index.cjs -->',
  'The map of every project, area, resource and archive entry, built from the folders and', 'the first sentence under each `card.md` title.',
  '', '## Projects', '', '- **acme/** — Move acme to the new provider.', '',
  '## Notes', '', '<!-- notes:start — kept as written on every rebuild -->', 'Ask Amina before archiving anything.', '<!-- notes:end -->', '',
].join('\n');

test('a new brain has no map file, and a session start makes none', (t) => {
  const box = newBrain(t);
  assert.equal(fs.existsSync(mapOf(box)), false);
  const out = start(box);
  assert.doesNotMatch(out.out, /context-index\.md/);
  assert.equal(fs.existsSync(mapOf(box)), false);
});

test('an older brain keeps its map file, marked once as no longer updated', (t) => {
  const box = newBrain(t);
  fs.writeFileSync(mapOf(box), OLD_MAP);
  git(box.brain, ['add', '-A']);
  git(box.brain, ['commit', '-q', '-m', 'an older brain']);
  const n = commits(box);

  const out = start(box);
  assert.equal(out.code, 0, out.err);
  const said = out.out.split('\n').filter((line) => /context-index\.md/.test(line));
  assert.equal(said.length, 1, out.out);
  assert.match(said[0], /is no longer updated: `cogby map` prints the map .* committed \([0-9a-f]{7,}\)/);
  const now = fs.readFileSync(mapOf(box), 'utf8');
  assert.match(now, /^# Context index\n\n<!-- retired: cogby map -->\n> This file is no longer updated\. `cogby map` prints the current map\. What is below is the map as it was on \d{4}-\d\d-\d\d, kept for the record\.\n\n<!-- generated by /);
  assert.equal(now.replace(/<!-- retired: cogby map -->\n> [^\n]+\n\n/, ''), OLD_MAP, 'everything that was in the file is still there');
  assert.equal(commits(box), n + 1);
  assert.equal(git(box.brain, ['show', '--name-only', '--format=', 'HEAD']), MAP_REL);

  // Once: the next start leaves the file as it is and says nothing.
  const again = start(box);
  assert.doesNotMatch(again.out, /context-index\.md/);
  assert.equal(fs.readFileSync(mapOf(box), 'utf8'), now);
  assert.equal(commits(box), n + 1);
});

test('a map file Cogby did not generate is the owner\'s: left as it is', (t) => {
  const box = newBrain(t);
  const own = '# Context index\n\n- **acme** — kept by hand\n';
  fs.writeFileSync(mapOf(box), own);
  assert.doesNotMatch(start(box).out, /context-index\.md/);
  assert.equal(fs.readFileSync(mapOf(box), 'utf8'), own);
});

test('nothing in the plugin sends a session to the map file', () => {
  for (const file of ['AGENTS.md', '.claude/skills/capture/SKILL.md', '.claude/skills/plan-page/SKILL.md', 'core/templates/starter-brain/.cogby/self/SOUL.md']) {
    const text = fs.readFileSync(path.join(ROOT, file), 'utf8');
    assert.doesNotMatch(text, /context-index/, file);
    assert.match(text, /`cogby map`/, file);
  }
  assert.equal(fs.existsSync(path.join(ROOT, 'core', 'templates', 'starter-brain', '.cogby', 'context-index.md')), false);
});
